//
//  PlaceholderRenderer.swift
//  LiveLoopExtension
//
//  Draws the "open LiveLoop" card the virtual camera shows whenever the app is
//  not actively feeding frames. Kept to CoreGraphics + CoreText so it works
//  inside the sandboxed extension without AppKit / window-server access.
//

import Foundation
import CoreVideo
import CoreGraphics
import CoreText
import ImageIO
import os.log

private let logger = Logger(subsystem: "com.adrbn.LiveLoop.Extension", category: "Placeholder")

final class PlaceholderRenderer {

    private let colorSpace = CGColorSpaceCreateDeviceRGB()

    /// The app icon's tile, so callers see which app to open. Generated by
    /// scripts/make_icon.py --tile and decoded once; the card works without it.
    private lazy var icon: CGImage? = {
        guard let url = Bundle(for: PlaceholderRenderer.self).url(forResource: "PlaceholderIcon", withExtension: "png"),
              let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else {
            logger.error("PlaceholderIcon.png is missing from the extension bundle")
            return nil
        }
        return image
    }()

    /// The user's own off-air picture (app-fitted to the output size), kept in
    /// the extension's container so it survives restarts. Nil = the default card.
    private var customImage: CGImage?

    private static let customImageURL: URL? = {
        guard let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first else {
            return nil
        }
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("OffAirPicture.jpg")
    }()

    init() {
        if let url = Self.customImageURL, let data = try? Data(contentsOf: url) {
            apply(data)
        }
    }

    /// Replaces the off-air picture (empty data restores the default card) and saves it.
    func setCustomImage(_ data: Data) {
        guard let url = Self.customImageURL else { return }
        if data.isEmpty {
            customImage = nil
            try? FileManager.default.removeItem(at: url)
            return
        }
        guard data.count <= LiveLoop.OffAirPicture.maxBytes, apply(data) else {
            logger.error("Ignored an off-air picture that is too large or not an image (\(data.count) bytes)")
            return
        }
        do {
            try data.write(to: url, options: .atomic)
        } catch {
            logger.error("Couldn't save the off-air picture: \(error.localizedDescription, privacy: .public)")
        }
    }

    /// Decodes `data` into the picture to draw; false (and no change) if it isn't an image.
    @discardableResult
    private func apply(_ data: Data) -> Bool {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              // Decode once now, not on every 30 fps draw.
              let image = CGImageSourceCreateImageAtIndex(
                source, 0, [kCGImageSourceShouldCacheImmediately: true] as CFDictionary) else { return false }
        customImage = image
        return true
    }

    /// Renders the placeholder card directly into a BGRA pixel buffer.
    func draw(into pixelBuffer: CVPixelBuffer) {
        CVPixelBufferLockBaseAddress(pixelBuffer, [])
        defer { CVPixelBufferUnlockBaseAddress(pixelBuffer, []) }

        let width = CVPixelBufferGetWidth(pixelBuffer)
        let height = CVPixelBufferGetHeight(pixelBuffer)
        guard let base = CVPixelBufferGetBaseAddress(pixelBuffer) else { return }
        let bytesPerRow = CVPixelBufferGetBytesPerRow(pixelBuffer)

        let bitmapInfo = CGImageAlphaInfo.premultipliedFirst.rawValue
            | CGBitmapInfo.byteOrder32Little.rawValue
        guard let ctx = CGContext(data: base,
                                  width: width,
                                  height: height,
                                  bitsPerComponent: 8,
                                  bytesPerRow: bytesPerRow,
                                  space: colorSpace,
                                  bitmapInfo: bitmapInfo) else { return }

        let w = CGFloat(width)
        let h = CGFloat(height)

        if let customImage {
            ctx.interpolationQuality = .high
            ctx.draw(customImage, in: CGRect(x: 0, y: 0, width: w, height: h))
            return
        }

        // Background — LiveLoop's near-black navy.
        ctx.setFillColor(red: 0.055, green: 0.067, blue: 0.098, alpha: 1)
        ctx.fill(CGRect(x: 0, y: 0, width: w, height: h))

        // The app icon above the wordmark.
        if let icon {
            let side = (h * 0.17).rounded()
            ctx.interpolationQuality = .high
            ctx.draw(icon, in: CGRect(x: ((w - side) / 2).rounded(), y: (h * 0.545).rounded(),
                                      width: side, height: side))
        }

        drawCentered("LiveLoop",
                     fontSize: h * 0.085,
                     baselineY: h * 0.44,
                     color: CGColor(red: 1, green: 1, blue: 1, alpha: 1),
                     bold: true, ctx: ctx, width: w)
        drawCentered("Open the app to go live",
                     fontSize: h * 0.034,
                     baselineY: h * 0.36,
                     color: CGColor(red: 0.58, green: 0.64, blue: 0.74, alpha: 1),
                     bold: false, ctx: ctx, width: w)
    }

    private func drawCentered(_ string: String,
                              fontSize: CGFloat,
                              baselineY: CGFloat,
                              color: CGColor,
                              bold: Bool,
                              ctx: CGContext,
                              width: CGFloat) {
        let fontName = bold ? "HelveticaNeue-Bold" : "HelveticaNeue"
        let font = CTFontCreateWithName(fontName as CFString, fontSize, nil)
        let attributes: [NSAttributedString.Key: Any] = [
            NSAttributedString.Key(kCTFontAttributeName as String): font,
            NSAttributedString.Key(kCTForegroundColorAttributeName as String): color,
        ]
        let attributed = NSAttributedString(string: string, attributes: attributes)
        let line = CTLineCreateWithAttributedString(attributed)
        var ascent: CGFloat = 0, descent: CGFloat = 0, leading: CGFloat = 0
        let textWidth = CGFloat(CTLineGetTypographicBounds(line, &ascent, &descent, &leading))
        ctx.textMatrix = .identity
        ctx.textPosition = CGPoint(x: (width - textWidth) / 2, y: baselineY)
        CTLineDraw(line, ctx)
    }
}
